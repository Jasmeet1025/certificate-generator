// Bundles the three certificate fonts into src/fonts.ts, so the generator needs no font files at run time
// (works the same on a server, in a serverless function or in a script). Run by `npm run build`.
import { readFileSync, writeFileSync } from "node:fs";

const fonts = {
  name: "GreatVibes-Regular.ttf", // the participant's name
  location: "Montserrat-BoldItalic.ttf", // "course conducted at"
  label: "OpenSans-BoldItalic.ttf", // training date and certificate number
};

const lines = Object.entries(fonts).map(([key, file]) => {
  const b64 = readFileSync(new URL(`../fonts/${file}`, import.meta.url)).toString("base64");
  return `  /** ${file} (SIL Open Font License, fonts/${file.split("-")[0]}-OFL.txt) */\n  ${key}: "${b64}",`;
});

writeFileSync(
  new URL("../src/fonts.ts", import.meta.url),
  `// Generated by scripts/embed-fonts.mjs — do not edit.\nexport const FONTS_BASE64: Record<"name" | "location" | "label", string> = {\n${lines.join("\n")}\n};\n`,
);
console.log("src/fonts.ts written");
